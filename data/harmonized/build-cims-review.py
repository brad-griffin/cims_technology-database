"""Write cims-review.md: what to rename, merge, remove and add in CIMS.

Run from the repo root:   python data/harmonized/build-cims-review.py

Reads cims-map.csv and technology.csv; writes cims-review.md.  Everything in
the document is derived, so re-running it after the mapper changes keeps the
advice and the data in step.
"""
from __future__ import annotations

import csv, difflib, re, collections
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = lambda n: list(csv.DictReader((HERE / n).open(encoding="utf-8-sig")))

CARRIER_WORDS = r"(ng|natural gas|oil|hfo|heavy fuel oil|electric|electricity|coal|petcoke|" \
                r"biomass|hydrogen|h2|diesel|propane|steam|rng|renewable natural gas)"


def main() -> None:
    m = R("cims-map.csv")
    techs = R("technology.csv")
    by_action = collections.Counter(r["action"] for r in m)
    ind = [r for r in m if r["action"] != "out-of-scope"]

    # --- near-duplicate names within one service node --------------------
    groups = collections.defaultdict(list)
    for r in ind:
        groups[(r["cims-sector"], r["cims-service"])].append(r["cims-technology"])
    typos, carrierless = [], []
    for (sec, svc), names in sorted(groups.items()):
        uniq = sorted(set(names))
        for i, a in enumerate(uniq):
            for b in uniq[i + 1:]:
                ratio = difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio()
                if ratio > 0.9 and a.lower() != b.lower():
                    typos.append((sec, svc, a, b, round(ratio, 3)))
            # 'recuperated reheat furnace' beside 'NG recuperated reheat furnace'
            for b in uniq:
                if b.lower() != a.lower() and b.lower().endswith(a.lower()) and \
                   re.fullmatch(CARRIER_WORDS + r" ?", b[:-len(a)].lower().strip() + " "):
                    carrierless.append((sec, svc, a, b))

    lower = sorted({(r["cims-sector"], r["cims-technology"]) for r in ind
                    if r["cims-technology"] and r["cims-technology"][0].islower()})
    bare = sorted({(r["cims-sector"], r["cims-service"], r["cims-technology"]) for r in ind
                   if r["action"] == "fuel-node"})
    unmapped = sorted({(r["cims-sector"], r["cims-service"], r["cims-technology"]) for r in ind
                       if r["action"] == "review"})
    subtype = [r for r in ind if r["action"] == "merge-review"]

    # --- in our database but not in CIMS ---------------------------------
    cims_names = {r["technology"] for r in m if r["technology"]}
    missing = [t for t in techs if t["technology"] not in cims_names]

    def tbl(header, rows, widths=None):
        out = ["| " + " | ".join(header) + " |", "| " + " | ".join("-" for _ in header) + " |"]
        for r in rows:
            out.append("| " + " | ".join(str(x).replace("|", "\\|") for x in r) + " |")
        return "\n".join(out)

    L = []
    A = L.append
    A("# CIMS technology review")
    A("")
    A("Generated by `data/harmonized/build-cims-review.py` from `cims-map.csv`, which is")
    A("itself generated by `build-cims-map.py` from the CIMS model inputs in")
    A("`data_processing_calibration/cims/data/model_inputs/model/`. Re-run both after")
    A("changing the mapping rules — nothing here is hand-maintained.")
    A("")
    A("## 1. What the mapping found")
    A("")
    A(tbl(["Outcome", "Rows", "What it means"], [
        ("`retain`", by_action["retain"],
         "maps cleanly onto one harmonized technology; keep the technology, rename it"),
        ("`merge`", by_action["merge"],
         "same device as another row at the same service node, differing only in efficiency wording — the `efficiency-*` variant already carries that"),
        ("`merge-review`", by_action["merge-review"],
         "collapses onto another row, but CIMS draws a sub-type distinction the harmonized name does not — **needs a decision**"),
        ("`fuel-node`", by_action["fuel-node"],
         "CIMS models a fuel choice as a technology; there is no device to name"),
        ("`review`", by_action["review"],
         "no equipment or carrier keyword matched — **needs a human**"),
        ("`out-of-scope`", by_action["out-of-scope"],
         "residential, commercial, transport or electricity supply; outside this database's industrial scope"),
    ]))
    A("")
    A(f"{len(ind)} industrial CIMS technologies reduce to "
      f"{len({r['technology'] for r in ind if r['technology']})} distinct harmonized names.")
    A("")
    A("## 2. Rename: all of them")
    A("")
    A("No CIMS technology name follows the repo convention (`equipment_carrier_variant`,")
    A("lowercase, hyphens within a component). The proposed name for every row is in the")
    A("`technology` column of `cims-map.csv`. The renaming is mechanical for the")
    A(f"{by_action['retain']} `retain` rows; the rest need the decisions below first.")
    A("")
    A("Worked examples:")
    A("")
    ex = [r for r in ind if r["action"] == "retain" and r["technology"]][:12]
    A(tbl(["CIMS sector", "CIMS service", "CIMS technology", "Proposed name"],
          [(r["cims-sector"], r["cims-service"], r["cims-technology"], f"`{r['technology']}`")
           for r in ex]))
    A("")
    A("## 3. Remove or fix: probable typos and duplicates")
    A("")
    if typos:
        A("Names more than 90% similar inside the same service node. Most are a spelling")
        A("slip or an unprefixed twin, not two real technologies.")
        A("")
        A(tbl(["Sector", "Service", "Name A", "Name B", "Similarity"],
              [(a, b, f"`{c}`", f"`{d}`", e) for a, b, c, d, e in typos[:30]]))
        if len(typos) > 30:
            A("")
            A(f"…and {len(typos) - 30} more; the full set is reproducible from this script.")
    A("")
    if carrierless:
        A("### Unprefixed twins")
        A("")
        A("A technology that exists both with and without a carrier prefix at the same node.")
        A("The unprefixed one is almost certainly a leftover: it cannot be told apart from")
        A("its siblings once the model is read by anyone but its author.")
        A("")
        A(tbl(["Sector", "Service", "Unprefixed", "Prefixed sibling"],
              [(a, b, f"`{c}`", f"`{d}`") for a, b, c, d in carrierless[:20]]))
    A("")
    if lower:
        A("### Case inconsistency")
        A("")
        A(f"{len(lower)} technologies are lower-case where the rest of the model is title case, "
          "e.g. " + ", ".join(f"`{t}`" for _, t in lower[:6]) + ".")
    A("")
    A("## 4. Decide: sub-type distinctions the naming convention drops")
    A("")
    A(f"{len(subtype)} rows collapse onto another technology at the same service node because")
    A("the harmonized name has no slot for the sub-type CIMS names. Either add variant terms")
    A("to section 6.2 of the design document, or accept the merge and lose the distinction.")
    A("")
    fam = collections.Counter()
    for r in subtype:
        fam[r["equipment"] or "(unmapped)"] += 1
    A(tbl(["Equipment family", "Rows affected", "Example distinction CIMS makes"],
          [(f"`{k}`", v, {
              "motor": "AC vs DC vs synchronous vs DC solid state",
              "fan": "airfoil vs backward-inclined vs vane-axial / tube-axial",
              "pump": "centrifugal vs rotary vs reciprocating",
              "compressor": "centrifugal vs rotary vs reciprocating vs screw",
              "conveyor": "belt vs screw vs apron",
              "kiln": "rotary preheat vs rotary preheat with internals",
              "roaster": "flash vs fluidised bed vs hearth",
              "converter": "Pierce-Smith vs top-blown rotary",
          }.get(k, "see `note` in cims-map.csv"))
           for k, v in fam.most_common(12)]))
    A("")
    A("The motor, pump, fan, compressor and conveyor families are the bulk of this. They are")
    A("also where CIMS carries size classes (`Size 1`…`Size 6`, `Small`/`Large`) as separate")
    A("service nodes, which the harmonized layer preserves as `process-step` — so size is not")
    A("at risk here, only sub-type.")
    A("")
    A("## 5. Structural: fuel choices modelled as technologies")
    A("")
    A(f"{len(bare)} CIMS technologies are a bare fuel name — `NG`, `Electric`, `H2`,")
    A("`Renewable Natural Gas`, `Heavy Fuel Oil`, `Thermal Coal`. There is no device to name.")
    A("In the harmonized layer these are `tech-flow` input rows on the parent technology, not")
    A("technologies. Keeping them as technologies in CIMS is a modelling choice, not an error —")
    A("but it is why a straight name-for-name port will not work.")
    A("")
    A(tbl(["Sector", "Service", "CIMS technology"],
          [(a, b, f"`{c}`") for a, b, c in bare[:15]]))
    A("")
    A("## 6. Needs a human: unmapped")
    A("")
    A(f"{len(unmapped)} industrial rows matched no equipment or carrier keyword. Several are")
    A("process names the mapper has no vocabulary for; a few are placeholders in CIMS itself")
    A("(`Existing`, `Reference`, `Std`, `Unassigned Energy`) that are candidates for removal.")
    A("")
    A(tbl(["Sector", "Service", "CIMS technology"],
          [(a, b, f"`{c}`") for a, b, c in unmapped[:30]]))
    A("")
    A("## 7. Missing from CIMS")
    A("")
    A(f"{len(missing)} technologies in the harmonized database have no CIMS counterpart.")
    A("These are the additions worth considering, and the reason the database is worth having.")
    A("")
    ph = [t for t in missing if t["status"] == "placeholder"]
    have = [t for t in missing if t["status"] != "placeholder"]
    A(f"**{len(have)} with data already extracted** — these can be added to CIMS now:")
    A("")
    A(tbl(["Technology", "Label", "Source"],
          [(f"`{t['technology']}`", t["technology-label"][:60], t["source-id"]) for t in have]))
    A("")
    A(f"**{len(ph)} placeholders** — named in the design document as in scope, no local source yet:")
    A("")
    A(", ".join(f"`{t['technology']}`" for t in ph))
    A("")
    A("The placeholders are concentrated in exactly the places a 20-year-old technology set")
    A("would be thin: electric and hydrogen heat (`boiler_electricity`, `boiler_hydrogen`,")
    A("`resistance-heater_electricity_*`, `induction-heater_electricity`), industrial heat")
    A("pumps and mechanical vapour recompression, solar thermal, and nuclear process heat.")
    A("")
    (HERE / "cims-review.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"cims-review.md written: {len(L)} lines")
    print(f"  typos/near-duplicates {len(typos)}, unprefixed twins {len(carrierless)}, "
          f"sub-type merges {len(subtype)}, fuel-nodes {len(bare)}, unmapped {len(unmapped)}, "
          f"missing from CIMS {len(missing)}")


if __name__ == "__main__":
    main()
