def _slug(x: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (x or "").lower()).strip("-")


def num(v):
    try:
        f = float(str(v).replace(",", ""))
        return f if f == f and abs(f) != float("inf") else None
    except (TypeError, ValueError):
        return None


def fmt(x):
    if x is None:
        return ""
    return f"{x:.6g}"


def citation_map():
    """citation string -> source-id, from ukerc-citations.py."""
    p = HERE / "ukerc_2013_usable-energy-database_citations.csv"
    if not p.exists():
        return {}
    return {r["citation"]: r["source-id"]
            for r in csv.DictReader(p.open(encoding="utf-8")) if r["source-id"]
            and r["source-id"] != "unattributed"}


def originals(text, cmap):
    """The source-ids behind a UKERC reference string, best effort, in order."""
    if not text:
        return ""
    import importlib.util as _i
    spec = _i.spec_from_file_location("uc", HERE / "ukerc-citations.py")
    mod = _i.module_from_spec(spec); spec.loader.exec_module(mod)
    out = []
    for c in mod.parse(text):
        sid = cmap.get(mod.norm(c))
        if sid and sid not in out:
            out.append(sid)
    return ";".join(out)


def main() -> int:
    if not SRC.exists():
        sys.exit(f"{SRC.name} not found -- run ukerc-dump.py first")
    raw = list(csv.DictReader(SRC.open(encoding="utf-8")))

    # ---- reshape into one dict per UKERC technology ----------------------
    tech: dict[tuple, dict] = collections.defaultdict(dict)
    flows: dict[tuple, list] = collections.defaultdict(list)
    typo_hits = collections.Counter()
    for r in raw:
        key = (r["table"], r["ukerc-id"])
        grp, name, unit, val = (r["column-group"], r["column-name"],
                                r["column-unit"], r["value"])
        for bad, good in TYPOS.items():
            if grp == bad or val == bad:
                typo_hits[bad] += 1
                grp = good if grp == bad else grp
                val = good if val == bad else val
        d = tech[key]
        d.setdefault("description", r["technology-description"])
        d.setdefault("baseline", r["baseline-applicable"])
        if grp == "References related to technology data":
            d.setdefault("ref-tech", val)
        if grp == "Technology costs" and name == "Reference":
            d.setdefault("ref-cost", val)
        if grp in ("Technology energy inputs", "Technology energy outputs",
                   "Technology non-energy inputs", "Technology non-energy outputs",
                   "Technology input", "Technology output"):
            flows[key].append((grp, name, unit, val))
        else:
            d[(grp, name)] = (val, unit)
    return finish(tech, flows, typo_hits)


def is_measure(d) -> bool:
    """A UKERC row is an efficiency measure, not a technology of its own, when
    it is Additional to its baseline and Evolutionary in degree of change."""
    rel = (d.get(("Technical limitations", "Nature of relationship with baseline"),
                 ("", ""))[0] or "").strip().lower()
    chg = (d.get(("Market limitations on adoption", "Degree of technological change"),
                 ("", ""))[0] or "").strip().lower()
    return rel == "additional" and chg == "evolutionary"


def get(d, group, *names):
    for n in names:
        if (group, n) in d:
            return d[(group, n)]
    for k, v in d.items():
        if not isinstance(k, tuple):     # the dict also holds plain metadata keys
            continue
        g, n = k
        if g == group and any(n.startswith(x[:24]) for x in names):
            return v
    return ("", "")


def sec_of(d, group):
    v, u = get(d, group, "SEC (final basis)")
    return num(v), u


def saving_fraction(d):
    """Energy saving against the baseline, as a fraction. None when either SEC
    is missing or the baseline is zero."""
    b, _ = sec_of(d, "Baseline net energy demand and emissions")
    t, _ = sec_of(d, "Technology net energy demand and emissions")
    if b in (None, 0) or t is None:
        return None
    return (b - t) / b


def finish(tech, flows, typo_hits):
    PCOLS = ["process", "technology", "parameter", "target", "unit", "value",
             "value-min", "value-max", "formula", "reference", "source-original", "note"]
    FCOLS = ["process", "technology", "direction", "commodity", "value", "unit",
             "per-unit", "value-min", "value-max", "co-product", "formula",
             "reference", "source-original", "note"]
    CCOLS = ["process", "technology", "constraint", "region", "year", "value",
             "unit", "constraint-basis", "reference", "source-original", "note"]
    params, flowrows, cons = [], [], []
    named: dict[tuple, dict] = {}
    buckets: dict[tuple, list] = collections.defaultdict(list)
    unnamed = []

    # ---- 1. name every UKERC row ---------------------------------------
    for key, d in tech.items():
        table, uid = key
        sector = SECTOR[table]
        step = d.get("baseline", "")
        desc = d.get("description", "")
        equip, carrier, variant, end_use, conf, note, kind = cims_map.classify(
            table, step, desc)
        step_eq, step_carrier, _, _, _, _, _ = cims_map.classify(table, "", step)
        if is_measure(d) and step_eq:
            # An efficiency measure belongs to the device at its process step.
            # Reading equipment out of the measure's own wording puts "coke dry
            # quenching" on a dryer and "waste fuel from the cold rolling plant"
            # on a rolling mill, when both are measures on other equipment.
            equip = step_eq
            carrier = carrier or step_carrier
        elif not equip:
            equip = step_eq
            carrier = carrier or step_carrier
        d.update({"sector": sector, "step": step, "equip": equip, "carrier": carrier,
                  "variant": variant, "end-use": end_use, "uid": uid, "table": table})
        if is_measure(d):
            buckets[(sector, step, equip, carrier)].append((key, d))
        else:
            name = "_".join(x for x in (equip, carrier, variant) if x)
            if not name:
                unnamed.append((uid, desc, step))
                continue
            # UKERC files the alternative binders (C-CS2 to C-CS6) under the kiln
            # step; each is its own binder route (modeller, 2026-09-26)
            name = BINDER_ROWS.get(uid, name)
            named[key] = dict(d, name=name)

    # ---- 2. bucket the measures ----------------------------------------
    bucket_members = collections.defaultdict(list)
    for (sector, step, equip, carrier), members in buckets.items():
        if not equip:
            for key, d in members:
                unnamed.append((d["uid"], d["description"], step))
            continue
        for key, d in members:
            f = saving_fraction(d)
            tier = "efficiency-strong" if (f is not None and f >= 0.15) else \
                   "efficiency-moderate"
            name = "_".join(x for x in (equip, carrier, tier) if x)
            bucket_members[(sector, step, name)].append((key, d, f))

    # ---- 3. emit ---------------------------------------------------------
    cmap = citation_map()
    # UKERC cites its cost data and its technical data separately, so a row
    # takes whichever applies. Set once per technology or bucket rather than
    # threaded through every call.
    cur = {"cost": "", "tech": ""}

    def emit_param(step, name, param, value, unit="", target="", vmin="", vmax="",
                   formula="", ref="", note="", src=None):
        if value == "" and formula == "" and note == "":
            return
        if src is None:
            src = cur["cost"] if param.startswith(
                ("capex", "opex", "decommissioning", "capital-recovery")) else cur["tech"]
            src = src or cur["tech"] or cur["cost"]
        params.append(dict(zip(PCOLS, [step, name, param, target, unit, value,
                                       vmin, vmax, formula, ref, src, note])))

    def common(step, name, d, ref, note_prefix):
        mat = (get(d, "Market limitations on adoption", "Technological maturity level")[0]
               or "").strip().lower()
        sod = MATURITY.get(mat, "")
        if sod:
            emit_param(step, name, "state-of-development", sod, ref=ref,
                       note=note_prefix + f"UKERC maturity level {mat!r}")
            emit_param(step, name, "trl", TRL[sod], ref=ref,
                       note=note_prefix + "derived from the UKERC maturity level, not a "
                       "source value: Commercial -> 9, Demonstration -> 6, R&D -> 4")
        yr = get(d, "Market limitations on adoption",
                 "Expected commericalisation year (blank indicates alr")[0]
        if yr and str(yr).strip().lower() not in ("n/a", "na", "-"):
            emit_param(step, name, "year-available", str(yr).strip(), unit="year", ref=ref,
                       note=note_prefix + "UKERC expected commercialisation year; blank in "
                       "the source means already commercialised")
        lt = num(get(d, "Technology costs", "Lifetime")[0])
        if lt is not None:
            emit_param(step, name, "lifetime", fmt(lt), unit="years", ref=ref,
                       note=note_prefix)
        sec, secu = sec_of(d, "Technology net energy demand and emissions")
        if sec is not None:
            emit_param(step, name, "specific-energy-consumption", fmt(sec),
                       unit=secu or "GJ/unit", ref=ref,
                       note=note_prefix + "final-energy basis, per unit of the baseline "
                       f"output ({d.get('baseline-unit', 'see UKERC')})")
        return sec

    def emit_costs(step, name, d, ref, note_prefix, sec, unit_out):
        cap = num(get(d, "Technology costs", "Capital cost")[0])
        cmin = num(get(d, "Technology costs", "Capital cost - Minimum")[0])
        cmax = num(get(d, "Technology costs", "Capital cost - Maximum")[0])
        if cap is not None:
            emit_param(step, name, "capex", fmt(cap),
                       unit=f"{CURRENCY}/{unit_out}-per-yr", vmin=fmt(cmin), vmax=fmt(cmax),
                       ref=ref,
                       note=note_prefix + "AS REPORTED. COST BASIS: installed. UKERC states "
                       "capital cost per unit of baseline output per year, not per unit of "
                       "capacity - the denominator is annual product, so this is already a "
                       "per-annual-capacity cost in product terms. Minimum and maximum are "
                       "UKERC's own range.")
            if sec:
                emit_param(step, name, "capex", "",
                           unit=f"{CURRENCY}/GJ-per-yr",
                           formula=f"{cap:.6g} / {sec:.6g}", ref=ref,
                           note=note_prefix + "DERIVED from the as-reported capex by dividing "
                           "by the technology's specific energy consumption, giving cost per "
                           "unit of annual energy throughput. Stored alongside the as-reported "
                           "row so UKERC can be compared with the per-kW sources without "
                           "either being converted away. COST BASIS: installed.")
        for src, dst in (("O&M Fixed", "opex-fixed"), ("O&M cost", "opex-variable")):
            v = num(get(d, "Technology costs", src)[0])
            if v is None:
                continue
            emit_param(step, name, dst, fmt(v), unit=f"{CURRENCY}/{unit_out}-per-yr",
                       vmin=fmt(num(get(d, "Technology costs", src + " - Minimum")[0])),
                       vmax=fmt(num(get(d, "Technology costs", src + " - Maximum")[0])),
                       ref=ref, note=note_prefix + f"UKERC column {src!r}")

    def emit_emissions(step, name, d, ref, note_prefix):
        for col, (param, target) in EMISSION.items():
            for k, vu in d.items():
                if not isinstance(k, tuple):
                    continue
                g, n = k; v, u = vu
                if g != "Technology net energy demand and emissions" or n.lower() != col:
                    continue
                x = num(v)
                if x is None:
                    continue
                emit_param(step, name, param, fmt(x), target=target,
                           unit=u or "kgeCO2/unit", ref=ref,
                           note=note_prefix + f"UKERC column {n!r}" +
                           ("; this is the grid-electricity indirect term, not a "
                            "combustion factor" if "indirect" in n.lower() else "") +
                           ("; process emissions, not fuel combustion"
                            if "process" in n.lower() else ""))

    def emit_flows(step, name, key, d, ref, note_prefix):
        for grp, cname, unit, val in flows.get(key, []):
            x = num(val)
            if x is None or x == 0:
                continue
            com = COMMODITY.get(cname.strip().lower())
            if not com:
                continue
            direction = "output" if "output" in grp.lower() else "input"
            co = "yes" if (direction == "output" and
                           ("autogenerated" in cname.lower() or "exported" in cname.lower()
                            or com in ("blast-furnace-gas", "coke-oven-gas",
                                       "basic-oxygen-furnace-gas", "steam"))) else ""
            flowrows.append(dict(zip(FCOLS, [
                step, name, direction, com, fmt(x), unit or "GJ/unit",
                d.get("baseline-unit", "unit-baseline-output"), "", "", co, "", ref,
                originals(d.get("ref-tech", ""), cmap),
                note_prefix + f"UKERC column {cname!r} in {grp!r}"])))

    def emit_constraints(step, name, d, ref, note_prefix):
        pairs = [
            ("Current level of technology adoption, in reference to maximum technica",
             "current-adoption-share", "of-baseline-stock", ""),
            ("Applicability of technology to available baseline (maximum technical p",
             "applicability-to-stock", "of-baseline-stock", ""),
            ("Availability of technology to applicable baseline (maximum technical p",
             "applicability-to-stock", "of-baseline-stock", ""),
            ("Maximum further technical adoption", "max-adoption-share", "absolute", ""),
            ("Significant factory refit required", "refit-required", "", ""),
            ("Significant factory refit or shutdown/construction required",
             "refit-required", "", ""),
        ]
        for col, constraint, basis, _ in pairs:
            for k, vu in d.items():
                if not isinstance(k, tuple):
                    continue
                g, n = k; v, u = vu
                if not n.startswith(col[:40]):
                    continue
                if v == "" or str(v).strip().lower() in ("n/a", "na"):
                    continue
                cons.append(dict(zip(CCOLS, [step, name, constraint, "UK", "", str(v).strip(),
                                             u or "", basis, ref,
                                             originals(d.get("ref-tech", ""), cmap),
                                             note_prefix + f"UKERC column {n!r}"])))
        for yr in ("2020", "2030", "2040", "2050"):
            for k, vu in d.items():
                if not isinstance(k, tuple):
                    continue
                g, n = k; v, u = vu
                if not n.startswith(f"Expected adoption in {yr}"):
                    continue
                if num(v) is None:
                    continue
                cons.append(dict(zip(CCOLS, [step, name, "max-adoption-share", "UK", yr,
                                             fmt(num(v)), u or "%", "of-baseline-stock", ref,
                                             originals(d.get("ref-tech", ""), cmap),
                                             note_prefix + "UKERC expected adoption, in "
                                             "reference to maximum further technical potential"])))

    # distinct technologies -------------------------------------------------
    for key, d in named.items():
        cur["cost"] = originals(d.get("ref-cost", ""), cmap)
        cur["tech"] = originals(d.get("ref-tech", ""), cmap)
        ref = f"{d['table']}, row {d['uid']}"
        pre = f"UKERC {d['uid']}: {d['description']}. "
        unit_out = (get(d, "Basic technology and baseline information",
                        "Units of baseline output")[0] or "unit")
        d["baseline-unit"] = unit_out
        sec = common(d["step"], d["name"], d, ref, pre)
        emit_costs(d["step"], d["name"], d, ref, pre, sec, unit_out)
        emit_emissions(d["step"], d["name"], d, ref, pre)
        emit_flows(d["step"], d["name"], key, d, ref, pre)
        emit_constraints(d["step"], d["name"], d, ref, pre)

    # buckets ---------------------------------------------------------------
    for (sector, step, name), members in bucket_members.items():
        # a bucket's sources are the union of its members', best-cited first
        cs, ts = [], []
        for _, dm, _ in members:
            for x in originals(dm.get("ref-cost", ""), cmap).split(";"):
                if x and x not in cs:
                    cs.append(x)
            for x in originals(dm.get("ref-tech", ""), cmap).split(";"):
                if x and x not in ts:
                    ts.append(x)
        cur["cost"], cur["tech"] = ";".join(cs), ";".join(ts)
        ids = ", ".join(f"{d['uid']} ({d['description']})" for _, d, _ in members)
        savings = [f for _, _, f in members if f is not None]
        pre = (f"BUCKET of {len(members)} UKERC efficiency measures at this process step. "
               f"Members: {ids}. ")
        if savings:
            pre += (f"Energy saving against the UKERC baseline ranges "
                    f"{min(savings):.1%} to {max(savings):.1%}. ")
        ref = f"{members[0][1]['table']}, rows " + ", ".join(d['uid'] for _, d, _ in members)
        agg = {}
        for _, d, _ in members:
            for k, v in d.items():
                if isinstance(k, tuple):
                    agg.setdefault(k, []).append(v)
        # a bucket's value is the median of its members, with their range as min/max
        rep = {}
        for k, vals in agg.items():
            nums = [num(v) for v, _ in vals if num(v) is not None]
            unit = next((u for _, u in vals if u), "")
            if nums:
                rep[k] = (statistics.median(nums), min(nums), max(nums), unit, len(nums))
        d0 = dict(members[0][1])
        unit_out = (get(d0, "Basic technology and baseline information",
                        "Units of baseline output")[0] or "unit")
        d0["baseline-unit"] = unit_out

        def bagg(group, *names):
            for n in names:
                if (group, n) in rep:
                    return rep[(group, n)]
            return None

        AGGNOTE = ("Value is the MEDIAN across the bucket's members and min/max are their "
                   "range - a bucket aggregate, not a source value. The faithful per-measure "
                   "figures are in ukerc_2013_usable-energy-database_rows.csv. ")
        lt = bagg("Technology costs", "Lifetime")
        if lt:
            emit_param(step, name, "lifetime", fmt(lt[0]), unit="years", vmin=fmt(lt[1]),
                       vmax=fmt(lt[2]), ref=ref, note=pre + AGGNOTE)
        sec = bagg("Technology net energy demand and emissions", "SEC (final basis)")
        if sec:
            emit_param(step, name, "specific-energy-consumption", fmt(sec[0]),
                       unit=sec[3] or "GJ/unit", vmin=fmt(sec[1]), vmax=fmt(sec[2]),
                       ref=ref, note=pre + AGGNOTE)
        cap = bagg("Technology costs", "Capital cost")
        if cap:
            emit_param(step, name, "capex", fmt(cap[0]),
                       unit=f"{CURRENCY}/{unit_out}-per-yr", vmin=fmt(cap[1]),
                       vmax=fmt(cap[2]), ref=ref,
                       note=pre + AGGNOTE + "AS REPORTED. COST BASIS: installed.")
            if sec and sec[0]:
                emit_param(step, name, "capex", "", unit=f"{CURRENCY}/GJ-per-yr",
                           formula=f"{cap[0]:.6g} / {sec[0]:.6g}", ref=ref,
                           note=pre + AGGNOTE + "DERIVED per unit of annual energy "
                           "throughput, alongside the as-reported row. COST BASIS: installed.")
        om = bagg("Technology costs", "O&M Fixed")
        if om:
            emit_param(step, name, "opex-fixed", fmt(om[0]),
                       unit=f"{CURRENCY}/{unit_out}-per-yr", vmin=fmt(om[1]), vmax=fmt(om[2]),
                       ref=ref, note=pre + AGGNOTE)
        mats = collections.Counter()
        for _, d, _ in members:
            m = (get(d, "Market limitations on adoption", "Technological maturity level")[0]
                 or "").strip().lower()
            if m:
                mats[m] += 1
        if mats:
            sod = MATURITY.get(mats.most_common(1)[0][0], "")
            if sod:
                emit_param(step, name, "state-of-development", sod, ref=ref,
                           note=pre + f"most common maturity level among the members "
                           f"({dict(mats)})")
                emit_param(step, name, "trl", TRL[sod], ref=ref,
                           note=pre + "derived from the UKERC maturity level")
        for key, d, _ in members:
            emit_flows(step, name, key, d, ref,
                       f"BUCKET member {d['uid']} ({d['description']}). ")
            emit_constraints(step, name, d, ref,
                             f"BUCKET member {d['uid']} ({d['description']}). ")

    NCOLS = ["process", "technology", "sector", "end-use", "process-step", "service-unit"]
    nodes, seen_node = [], set()
    for src in (named.values(), ):
        for d in src:
            k = (d["step"], d["name"])
            if k in seen_node:
                continue
            seen_node.add(k)
            nodes.append(dict(zip(NCOLS, [d["step"], d["name"], d["sector"], d["end-use"],
                                          _slug(d["step"]),
                                          d.get("baseline-unit", "unit")])))
    for (sector, step, name), members in bucket_members.items():
        k = (step, name)
        if k in seen_node:
            continue
        seen_node.add(k)
        d0 = members[0][1]
        nodes.append(dict(zip(NCOLS, [step, name, sector, d0["end-use"], _slug(step),
                                      get(d0, "Basic technology and baseline information",
                                          "Units of baseline output")[0] or "unit"])))

    for path, cols, rows in (
            (HERE / "ukerc_2013_usable-energy-database_nodes.csv", NCOLS, nodes),
            (HERE / "ukerc_2013_usable-energy-database.csv", PCOLS, params),
            (HERE / "ukerc_2013_usable-energy-database_flows.csv", FCOLS, flowrows),
            (HERE / "ukerc_2013_usable-energy-database_constraints.csv", CCOLS, cons)):
        with path.open("w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=cols)
            w.writeheader(); w.writerows(rows)
        print(f"  {path.name:52s} {len(rows):5d} rows")

    with (HERE / "ukerc_2013_usable-energy-database_meta.csv").open(
            "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["parameter", "value"])
        w.writerow(["licence", "UKERC Energy Data Centre terms - check before redistribution"])
        w.writerow(["citation", "Griffin, P., Hammond, G., & Norman, J. (2013). Industrial "
                    "Energy Use and Carbon Emissions Reduction: A UK Perspective "
                    "(Usable Energy Database). University of Bath / UKERC"])
        w.writerow(["source-id", SOURCE_ID])

    print(f"\n  {len(named)} distinct technologies, {len(bucket_members)} efficiency buckets "
          f"covering {sum(len(v) for v in bucket_members.values())} UKERC measures")
    if unnamed:
        print(f"  {len(unnamed)} rows could not be named and were skipped:")
        for uid, desc, step in unnamed[:12]:
            print(f"      {uid:10s} {desc[:44]:44s} @ {step}")
    if typo_hits:
        print("  workbook typos normalised: " +
              ", ".join(f"{k!r} x{v}" for k, v in typo_hits.items()))
    return 0


