"""Turn the faithful UKERC dump into extraction files the harmonized layer reads.

Run from the repo root (after ukerc-dump.py):
    python data/raw-data/other-reports/ukerc-extract.py

Writes, beside the workbook:
    ukerc_2013_usable-energy-database.csv              parameters, template format
    ukerc_2013_usable-energy-database_flows.csv        energy and material flows
    ukerc_2013_usable-energy-database_constraints.csv  adoption and stock limits

What this does and does not carry, following design decisions D6-D8:

  * Only the TECHNOLOGY's own absolute values are kept. UKERC repeats every
    quantity four times -- baseline, technology, reduction, and net change --
    and storing more than one of those is how they drift apart. The baseline
    columns are recorded once per process step as their own `efficiency-base`
    technology, so nothing is lost; the reduction and net-change blocks are
    recomputable and are not stored.
  * Incremental efficiency measures are bucketed. A UKERC row that is
    'Additional' to its baseline and 'Evolutionary' in degree of change is a
    measure, not a technology: it is folded into the `efficiency-moderate` or
    `efficiency-strong` bucket for its process step, split at 15% energy saving,
    and named in that bucket's note. Everything else becomes its own technology.
  * Costs are stored twice, as agreed: once as reported (per unit of baseline
    output per year) and once derived per unit of annual energy throughput, so
    UKERC can be compared with the $/kW sources. The derived row carries the
    formula and points at the as-reported row through derived-from.

The workbook's own header typos are normalised here and listed at the end of
the run: 'Evolutionaru', 'Costs increase.', 'Reduction of energy outputss',
'Improvement potential rrror margin', 'commericalisation'.
"""
