"""The Excel workbook: written last, from the outputs, and never read back.

Banded sheets (the wide views, the archetype list and the source list) are laid
out like the UKTM sheet of the Bataille database: a dark header band (EMBER) with a
group band above it and a unit row below, each family as a large bold band row,
each equipment term as a bold `*` row beneath it, the rows indented under it.
The banding is the point: a banded sheet cannot be sorted or filtered without
breaking it, so it does not invite being used as a working table. The CSVs are
the machine-readable form. Every sheet opens at 75% zoom.
"""
from __future__ import annotations

import warnings

from .common import OUTPUT

ZOOM = 75
BOOK = OUTPUT / "technology-database.xlsx"
NUM_FORMAT = [(1000, "#,##0"), (100, "#,##0"), (10, "#,##0.0"),
              (1, "#,##0.00"), (0.1, "0.000"), (0.01, "0.0000")]
PLAIN_INT = {"trl", "year-available", "n-examples", "n"}
# identifiers and counts, not measurements: no thousands separator, no decimals
GENERAL = {"year", "rows-in-database"}
# columns whose values are left-justified whatever their type (trl mixes 9 and "5-8")
LEFT = {"trl"}
DETAIL = ("_low", "_high", "_n")

# Ember palette, lightest to darkest (Brad 2026-10-29)
EMBER = ["FFB58B", "F67A39", "C64E00", "971E00", "5A0C00"]
# How certain a value is, most certain first: tints of EMBER[1] with a third less
# chroma, at L* 58, 69, 79, 88, and 96 (about 14 units apart), so the steps read
# apart without the key (Brad 2026-10-29); a guess is unshaded grey italic and a
# parameter that does not apply is lighter grey. Keys are the fill grades plus
# `sourced` (as reported) and `converted` (sourced, external conversion factor).
SHADE = [
    ("sourced", "Sourced", "CA764C", None,
     "As the source reports it (units converted exactly)."),
    ("converted", "Sourced, converted", "DF9875", None,
     "Sourced, but converted with a factor from outside the source (a heating value, a "
     "density, a process ratio, or an assumption); see external-conversions."),
    ("identity", "Identity", "EEB89F", None, "Calculated from the archetype's own values."),
    ("estimated", "Estimated", "F8D6C6", None,
     "From other archetypes or a class rule fitted on this database."),
    ("proxy", "Proxy", "FEF1EB", None, "A class constant from an outside catalogue."),
    ("guess", "Guess", None, "7F7F7F", "A judgement, with a stated range and rationale."),
    ("not-applicable", "not applicable", None, "A6A6A6",
     "The parameter does not characterise the archetype."),
]

# the readme sheet: what used to repeat in every sheet's banner (Brad 2026-10-29)
README = [
    ("h", "Technology database"),
    ("p", "Generated by database/harmonized/build.py from database/harmonized/records/. Anything typed "
          "in this workbook is lost on the next build: edit the records instead."),
    ("h2", "Reading the values"),
    ("p", "Costs and intensities are per product-unit, so never compare them across families."),
    ("p", "Energy is on a higher heating value (HHV) basis."),
    ("p", "Central value: the median of three or more examples, otherwise the value from the "
          "highest-ranked source. Low and high are the widest values any example gives."),
    ("p", "The _low, _high, and _n columns are grouped beside each central column: use the + above "
          "a column to show them. _n is the number of examples pooled (0 for a filled value)."),
    ("p", "Hover over a column heading for its definition."),
    ("p", "The same tables without any fill are in database/harmonized/output/unfilled/."),
    ("h2", "Bands"),
    ("p", "The banded sheets run by family, then by end use in process order. Within an end use: "
          "conventional technologies, efficient variants, capture variants, then low-carbon "
          "alternatives. An archetype serving several end uses is repeated under each, in the "
          "family that owns that end use (see the families column)."),
    ("p", "Some end uses show an archetype per another unit than its own: per GJ of process heat, "
          "hydrogen per t, liquid fuels per m3, flaring per 1000 m3 of gas. The filled column names "
          "the factor. The long tables and the CSVs stay on the archetype's own unit."),
    ("p", "The bands break sorting and filtering, so the banded sheets are for reading. The flat "
          "sheets and the CSVs in database/harmonized/output/ are the working tables."),
    ("h2", "Shading: how certain a value is, most certain first"),
    ("legend", None),
    ("h2", "Sheets"),
    ("sheets", None),
]
SHEET_NOTES = {
    "wide-archetype": "One row per archetype in each end use: the main parameters.",
    "wide-carriers-species": "Energy by carrier and emissions by species.",
    "wide-flow": "Input and output flows.",
    "archetype": "The archetype list.",
    "source-list": "The sources.",
    "archetype-parameter": "Long table: one row per archetype, parameter, and target, with grade and method.",
    "archetype-flow": "Long table: one row per archetype flow.",
    "example": "The source examples behind each archetype.",
    "example-parameter": "Every source figure, as printed and normalised.",
    "example-flow": "Every source flow, as printed and normalised.",
    "example-constraint": "Source constraints (potentials, limits) by region and year.",
    "archetype-application": "Where each archetype applies in the CIMS hierarchy.",
}


def _fmt(v, col):
    if col in GENERAL:
        return "General"
    if col in PLAIN_INT or col.endswith("_n"):
        return "0"
    a = abs(v)
    if a == 0:
        return "0"
    for lo, f in NUM_FORMAT:
        if a >= lo:
            return f
    return "0.00E+00"


def _cell(v):
    if not isinstance(v, str) or v == "":
        return v
    try:
        return int(v) if v.lstrip("-").isdigit() else float(v)
    except ValueError:
        return v


def _put(ws, r, j, v):
    """Write a cell; a string beginning with `=` stays text (openpyxl would
    otherwise store it as a formula, which Excel rejects on opening)."""
    cell = ws.cell(r, j, v)
    if isinstance(v, str) and v.startswith("="):
        cell.data_type = "s"
    return cell


def write_book(banded: dict, flat: dict, families: dict, notes: dict | None = None,
               flags: dict | None = None, grades: dict | None = None,
               grouped: set | None = None, band_notes: dict | None = None) -> str:
    """`grouped`: sheets whose _low, _high and _n columns are put in an Excel
    outline group beside their central column, folded when the book opens.
    `flags`: {sheet: {(archetype, column)}} -- cells whose value rests on a
    conversion factor from outside the source.
    `grades`: {sheet: {(archetype, column): grade}} -- cells the fill step wrote.
    On the graded sheets every value is shaded by how certain it is (SHADE); the
    key is on the readme sheet, the first sheet of the book."""
    warnings.filterwarnings("ignore")
    import openpyxl
    from openpyxl.comments import Comment
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    # Ember palette (Brad 2026-10-29): headers in its two darkest shades, the folded
    # _low/_high/_n headers in its middle shade, the certainty shading in muted tints
    # of it (SHADE), family bands in a neutral warm grey so they never read as shading
    HEAD, HEAD_D = PatternFill("solid", fgColor=EMBER[3]), PatternFill("solid", fgColor=EMBER[4])
    # header of the folded _low/_high/_n columns (modeller 2026-10-09)
    DET, DET_D = PatternFill("solid", fgColor=EMBER[2]), PatternFill("solid", fgColor="A33E00")
    BAND, WARN = PatternFill("solid", fgColor="EFEBE8"), PatternFill("solid", fgColor="F4F1EF")
    f_head, f_grp = Font(sz=12, bold=True, color="FFFFFF"), Font(sz=10, bold=True, color="FFFFFF", italic=True)
    f_unit, f_band = Font(sz=10, color=EMBER[0]), Font(sz=16, bold=True, color=EMBER[4])
    f_sub, f_body = Font(sz=11, bold=True, color=EMBER[3]), Font(sz=11)
    f_warn = Font(sz=11, bold=True, color=EMBER[4])
    f_note = Font(sz=10, italic=True, color=EMBER[4])
    rule = Border(bottom=Side(style="thin", color=EMBER[3]))
    SHADE_FILL = {k: PatternFill("solid", fgColor=c) for k, _, c, _, _ in SHADE if c}
    SHADE_FONT = {k: Font(sz=11, italic=True, color=fc) for k, _, _, fc, _ in SHADE if fc}

    def shade(cell, key):
        if key in SHADE_FILL:
            cell.fill = SHADE_FILL[key]
        if key in SHADE_FONT:
            cell.font = SHADE_FONT[key]

    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    ws = wb.create_sheet("readme")
    ws.sheet_view.showGridLines = False
    ws.column_dimensions["A"].width = 2.5
    ws.column_dimensions["B"].width = 26
    ws.column_dimensions["C"].width = 173.57    # 1220 px (Brad 2026-10-29)
    r = 2
    for kind, text in README:
        if kind == "h":
            ws.cell(r, 2, text).font = Font(sz=18, bold=True, color=EMBER[4])
            r += 2
        elif kind == "h2":
            r += 1
            c = ws.cell(r, 2, text)
            c.font = Font(sz=13, bold=True, color="FFFFFF")
            for j in (2, 3):
                ws.cell(r, j).fill = HEAD
            r += 1
        elif kind == "p":
            c = ws.cell(r, 2, text)
            c.font, c.alignment = f_body, Alignment(wrap_text=True, vertical="top")
            ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=3)
            ws.row_dimensions[r].height = 15 * (1 + len(text) // 220)
            r += 1
        elif kind == "legend":
            for key, label, _, _, desc in SHADE:
                c = ws.cell(r, 2, label)
                c.font = f_body
                shade(c, key)
                ws.cell(r, 3, desc).font = f_body
                r += 1
            ws.cell(r, 2, "(none)").font = f_body
            ws.cell(r, 3, "Text, identifiers, and counts are not shaded.").font = f_body
            r += 1
        elif kind == "sheets":
            for name in list(banded) + list(flat):
                ws.cell(r, 2, name).font = Font(sz=11, bold=True)
                ws.cell(r, 3, SHEET_NOTES.get(name, "")).font = f_body
                r += 1
    for name, (cols, rows, groups, units, band, sub, banner) in banded.items():
        ws = wb.create_sheet(name)
        ws.sheet_view.showGridLines = False
        ws.column_dimensions["A"].width = 2.5
        first = 2
        ws.cell(1, 2, banner).font = f_warn
        for j in range(2, min(len(cols) + 2, 16)):
            ws.cell(1, j).fill = WARN
        ws.row_dimensions[1].height = 30
        for j, c in enumerate(cols, start=first):
            det = name in (grouped or ()) and c.endswith(DETAIL)
            for row_i, val, fill, font in ((3, groups.get(c, ""), DET_D if det else HEAD_D, f_grp),
                                           (4, c, DET if det else HEAD, f_head),
                                           (5, units.get(c, ""), DET if det else HEAD, f_unit)):
                cell = ws.cell(row_i, j, val)
                cell.fill, cell.font = fill, font
                cell.alignment = Alignment(horizontal="left", vertical="bottom", wrap_text=True)
                note = ((notes or {}).get(name) or {}).get(c) if row_i == 4 else None
                if note:
                    cell.comment = Comment(note, "technology database", width=320, height=160)
            ws.column_dimensions[get_column_letter(j)].width = (
                36 if j == first else 60 if c in ("full-citation", "applies-to", "description", "note")
                else max(10, min(20, len(c) + 3)))
        ws.row_dimensions[4].height = 46
        r, last_b, last_s = 7, None, None
        for row in rows:
            b, s = row.get(band, ""), row.get(sub, "") if sub else ""
            if b != last_b:
                r += 1
                ws.cell(r, first, families.get(b, b) or "(none)").font = f_band
                for j in range(first, len(cols) + first):
                    ws.cell(r, j).fill, ws.cell(r, j).border = BAND, rule
                if (band_notes or {}).get(b) and band in ("family", "_family"):
                    ws.cell(r, first + 1, band_notes[b]).font = f_note
                ws.row_dimensions[r].height = 22
                r += 1
                last_b, last_s = b, None
            if sub and s != last_s:
                ws.cell(r, first, f"*{s}").font = f_sub
                r += 1
                last_s = s
            for j, col in enumerate(cols, start=first):
                val = _cell(row.get(col, ""))
                cell = _put(ws, r, j, val)
                cell.font = f_body
                if name in (grades or {}):
                    key = grades[name].get((row.get("archetype"), col))
                    if key is None and (row.get("archetype"), col) in (flags or {}).get(name, ()):
                        key = "converted"
                    if (key is None and isinstance(val, (int, float)) and not isinstance(val, bool)
                            and groups.get(col, "identity") != "identity" and not col.endswith("_n")):
                        key = "sourced"
                    if key:
                        shade(cell, key)
                if j == first:
                    cell.alignment = Alignment(indent=1)
                elif isinstance(val, (int, float)) and not isinstance(val, bool):
                    cell.number_format = _fmt(val, col)
                    cell.alignment = Alignment(horizontal="left" if col in LEFT else "right")
                elif col in LEFT:
                    cell.alignment = Alignment(horizontal="left")
            r += 1
        ws.freeze_panes = ws.cell(6, first + 1).coordinate
        if name in (grouped or ()):
            # fold each parameter's _low/_high/_n run under its central column
            ws.sheet_properties.outlinePr.summaryRight = False
            run = []
            for j, c in enumerate(cols + [""], start=first):
                if c.endswith(DETAIL):
                    run.append(j)
                    continue
                if run:
                    ws.column_dimensions.group(get_column_letter(run[0]), get_column_letter(run[-1]),
                                               outline_level=1, hidden=True)
                    run = []
    for name, (cols, rows) in flat.items():
        ws = wb.create_sheet(name)
        ws.append(cols)
        for c in ws[1]:
            c.fill, c.font = HEAD, f_head
        for i, row in enumerate(rows, start=2):
            for j, c in enumerate(cols, start=1):
                _put(ws, i, j, _cell(row.get(c, "")))
        ws.freeze_panes = "B2"
        for j, c in enumerate(cols, start=1):
            ws.column_dimensions[get_column_letter(j)].width = max(10, min(40, len(c) + 4))
    for ws in wb.worksheets:
        ws.sheet_view.zoomScale = ZOOM
        ws.sheet_view.zoomScaleNormal = ZOOM
    try:
        wb.save(BOOK)
    except PermissionError:
        return "workbook is open in Excel; CSVs written, workbook not rebuilt"
    return f"{BOOK.name}: {len(wb.sheetnames)} sheets"
